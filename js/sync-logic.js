const WORD_COUNT = WORDS.length; // 512。Uint32 % WORD_COUNT が一様になるのは 2^32 が512の倍数のため。

/**
 * crypto.getRandomValues で 0 以上 exclusiveMax 未満の一様乱数を1つ取り出す。
 * exclusiveMax が 2^32 の約数でない場合は棄却サンプリングでバイアスを避ける。
 */
function randomUint32() {
  const arr = new Uint32Array(1);
  globalThis.crypto.getRandomValues(arr);
  return arr[0];
}

function randomWord() {
  // 2^32 は 512 の倍数なので % は完全に一様。棄却サンプリング不要(ブリーフの指定通り)。
  return WORDS[randomUint32() % WORD_COUNT];
}

function randomFourDigits() {
  // 2^32 は 10000 の倍数ではないため、単純な % 10000 は小さい余りに偏る。
  // 10000 の倍数として使える最大値を上限に棄却サンプリングし、一様性を保つ。
  const limit = Math.floor(0x1_0000_0000 / 10000) * 10000; // 4294960000
  let n;
  do {
    n = randomUint32();
  } while (n >= limit);
  return String(n % 10000).padStart(4, "0");
}

/**
 * 合言葉を新規生成する。単語4つ+4桁数字、区切りは「・」。
 * 例: "さくら・つばめ・ひかり・やま・4172"
 */
export function generatePassphrase() {
  const words = [randomWord(), randomWord(), randomWord(), randomWord()];
  return [...words, randomFourDigits()].join("・");
}

// 区切り文字とみなして「・」に統一する文字:
// 半角/全角スペース(\s は u フラグ付きで全角スペース U+3000 にもマッチする)、
// 読点(、)、半角カンマ(,)、全角カンマ(，)、半角中黒(･)、
// 「・」自身(連続を1つにまとめるため含める)。
// NFKCは使っていない(全角数字の変換と競合しうるため、区切り文字はここで個別に列挙する)。
const SEPARATOR_RE = /[\s、,，･・]+/gu;

/**
 * 人が読み上げた合言葉を再入力したときの表記ゆれを吸収する。
 * - 空白(半角/全角)・読点・カンマ(半角,/全角，)・半角中黒・「・」の連続 → 「・」1つに統一
 * - 全角数字 → 半角数字
 * - 前後の区切り文字を除去
 */
export function normalizePassphrase(input) {
  const halfWidthDigits = String(input).replace(/[０-９]/g, (ch) =>
    String.fromCharCode(ch.charCodeAt(0) - 0xfee0)
  );
  const unified = halfWidthDigits.replace(SEPARATOR_RE, "・");
  return unified.replace(/^・+|・+$/g, "");
}

/**
 * 合言葉から世帯ID(Firestoreのパスに使う決定的な識別子)を導出する。
 * SHA-256 の16進数表記(64文字)。同じ合言葉なら常に同じID、1文字違えば別ID。
 */
export async function householdIdFromPassphrase(pass) {
  const bytes = new TextEncoder().encode(pass);
  const digest = await globalThis.crypto.subtle.digest("SHA-256", bytes);
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

/**
 * updatedAt を比較可能な数値に変換する。undefined/null など欠損値は -Infinity として
 * 扱い、タイムスタンプを持つ側に必ず負けるようにする(0 を既定値にすると
 * 正当な updatedAt:0 のレコードと区別できなくなるため -Infinity を使う)。
 */
function comparableUpdatedAt(entity) {
  return entity.updatedAt ?? -Infinity;
}

/**
 * ローカルとリモートのエンティティ配列を id 単位の last-write-wins でマージする。
 * - 両方に存在する id: updatedAt が大きい方(同値なら remote)を採用。
 *   updatedAt が欠損している側は -Infinity 扱いとし、タイムスタンプを持つ側に必ず負ける。
 *   両方欠損なら同値扱いとなり remote が勝つ(既定のタイブレークと一貫させる)。
 * - local のみに存在する id: そのまま残す
 * - remote のみに存在する id: 末尾に追加
 * 出力の順序は local の並び順を保持し、remote 限定の id はその後ろに続く。
 * local・remote いずれの入力配列・要素も変更しない。
 */
export function mergeEntities(local, remote) {
  const remoteById = new Map(remote.map((entity) => [entity.id, entity]));
  const localIds = new Set(local.map((entity) => entity.id));

  const merged = local.map((localEntity) => {
    const remoteEntity = remoteById.get(localEntity.id);
    if (!remoteEntity) return localEntity;
    // 同値のときは remote を勝たせる(remoteはサーバー側の最新取り込みを表すため)。
    return comparableUpdatedAt(remoteEntity) >= comparableUpdatedAt(localEntity)
      ? remoteEntity
      : localEntity;
  });

  for (const remoteEntity of remote) {
    if (!localIds.has(remoteEntity.id)) merged.push(remoteEntity);
  }

  return merged;
}
